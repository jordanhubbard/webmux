// Package screenstate mirrors display output for a fresh terminal viewer.
// It does not execute input or replace a coding CLI's native session state.
package screenstate

import (
	"errors"
	"sync"

	"github.com/jordanhubbard/webmux/server/internal/replayfilter"
	"tuios.dev/vt"
	"tuios.dev/vt/snapshot"
)

const MaxSnapshotBytes = 2 << 20
const historyCells = 16 << 10

var ErrIncomplete = errors.New("terminal screen is between complete updates; retry attachment")
var ErrTooLarge = errors.New("terminal snapshot is too large; reduce the viewport and reconnect")
var ErrUnsupported = errors.New("terminal cursor cannot be restored safely; retain the existing job and recover manually")

type Screen struct {
	mu       sync.Mutex
	emulator *vt.Emulator
	filter   replayfilter.Filter
	closed   bool
}

// Image owns a copy of the screen at one output boundary. Encoding it may run
// after the caller registers a live-output queue and releases its owner lock.
type Image struct {
	state  *snapshot.State
	main   *underlay
	repeat bool
}

// The upstream capture includes the main cells, but only active-buffer margins
// and wrap flags. Retain those small pieces of the underlying screen as well.
type underlay struct {
	margins []int
	wraps   []bool
}

func validSize(cols, rows int) bool { return cols >= 1 && cols <= 500 && rows >= 1 && rows <= 200 }

func New(cols, rows int) (*Screen, error) {
	if !validSize(cols, rows) {
		return nil, errors.New("invalid terminal snapshot dimensions")
	}
	e := vt.NewEmulator(cols, rows)
	e.SetScrollbackMaxLines(min(512, max(1, historyCells/cols)))
	return &Screen{emulator: e, filter: replayfilter.Filter{Xterm: true}}, nil
}

func (s *Screen) Feed(data []byte) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return errors.New("terminal mirror is closed")
	}
	clean := s.filter.Feed(data)
	_, err := s.emulator.Write(clean)
	// The mirror is not an input authority. A live viewer answers queries;
	// responses generated by this second emulator must never reach the job.
	s.emulator.TakeResponses()
	return err
}

func (s *Screen) Resize(cols, rows int) error {
	if !validSize(cols, rows) {
		return errors.New("invalid terminal snapshot dimensions")
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return errors.New("terminal mirror is closed")
	}
	s.emulator.Resize(cols, rows)
	s.emulator.SetScrollbackMaxLines(min(512, max(1, historyCells/cols)))
	s.emulator.TakeResponses()
	return nil
}

func (s *Screen) Capture() (Image, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return Image{}, errors.New("terminal mirror is closed")
	}
	if !s.filter.AtBoundary() || s.emulator.IsSyncActive() {
		return Image{}, ErrIncomplete
	}
	state := snapshot.Capture(s.emulator, s.emulator.Width(), s.emulator.Height(), 512, 0)
	// Filtered input contains no partial controls. Refuse any parser state we
	// cannot account for rather than replaying a partial private request.
	if len(state.PendingInput) != 0 {
		return Image{}, ErrIncomplete
	}
	state.Title, state.IconName, state.TitleStack = "", "", nil
	state.TitlesKnown = false
	var main *underlay
	if state.IsAltScreen {
		// This switches the mirror's active buffer without executing a terminal
		// mode sequence or clearing cells. Feed/resize cannot interleave here.
		s.emulator.RestoreAltScreenMode(false)
		main = &underlay{wraps: make([]bool, state.Height)}
		r := s.emulator.ScrollRegion()
		main.margins = []int{r.Min.X, r.Min.Y, r.Dx(), r.Dy()}
		for y := range main.wraps {
			main.wraps[y], _ = s.emulator.RowSoftWrapped(y)
		}
		s.emulator.RestoreAltScreenMode(true)
	}
	return Image{state: state, main: main, repeat: s.filter.CanRepeat()}, nil
}

func (i Image) Bytes() ([]byte, error) {
	if i.state == nil {
		return nil, errors.New("terminal snapshot is missing")
	}
	// With autowrap disabled, this emulator clamps both a cursor addressed to
	// the final cell and one advanced past it to the same coordinate. Xterm
	// distinguishes them. Never guess which cell to reprint at this boundary.
	if !i.state.Modes[7] && i.state.CursorX == i.state.Width-1 {
		return nil, ErrUnsupported
	}
	data, err := replayScreen(i.state, i.main, i.repeat)
	if err != nil {
		return nil, err
	}
	if len(data) > MaxSnapshotBytes-3 {
		return nil, ErrTooLarge
	}
	return append([]byte("\x18\x1bc"), data...), nil
}

func (s *Screen) Close() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return nil
	}
	s.closed = true
	return s.emulator.Close()
}
