package session

import (
	"path/filepath"
	"strings"
	"time"
)

// Agent Deck's `session attach` (lipgloss v1 / termenv) probes the terminal
// background at startup: it writes an OSC 11 query followed by a
// cursor-position request, then waits up to five seconds for a reply while
// reading stdin raw and discarding everything else. WebMux's browser terminal
// deliberately never answers terminal queries, so every Agent Deck attach
// stalled and silently dropped early keystrokes (#325).
//
// Answer only that startup probe, only once, and only shortly after the attach
// process starts. The reply is a cursor-position report with no colour, so
// termenv treats OSC 11 as unsupported and falls back to its default instead of
// being told a background the user's terminal never reported.
const (
	attachProbeWindow      = 3 * time.Second
	attachProbeColorQuery  = "\x1b]11;?"
	attachProbeCursorQuery = "\x1b[6n"
	attachProbeCursorReply = "\x1b[1;1R"
)

type attachProbe struct {
	deadline time.Time
	pending  string // bounded unmatched suffix spanning PTY read boundaries
	sawColor bool
}

// agentDeckAttachArgv matches the attach commands the coordination provider
// builds: `agent-deck [-p profile] session attach <id>` and
// `agent-deck remote attach <remote> <id>`.
func agentDeckAttachArgv(argv []string) bool {
	if len(argv) < 3 || filepath.Base(argv[0]) != "agent-deck" {
		return false
	}
	for i := 1; i+1 < len(argv); i++ {
		if (argv[i] == "session" || argv[i] == "remote") && argv[i+1] == "attach" {
			return true
		}
	}
	return false
}

func newAttachProbe(argv []string, now time.Time) *attachProbe {
	if !agentDeckAttachArgv(argv) {
		return nil
	}
	return &attachProbe{deadline: now.Add(attachProbeWindow)}
}

// feed inspects raw PTY output. It reports whether the cursor-position reply
// should be sent, and whether the probe is finished and can be discarded.
func (p *attachProbe) feed(data string, now time.Time) (answer, done bool) {
	if now.After(p.deadline) {
		return false, true
	}
	text := p.pending + data
	if !p.sawColor {
		index := strings.Index(text, attachProbeColorQuery)
		if index < 0 {
			p.pending = suffix(text, len(attachProbeColorQuery)-1)
			return false, false
		}
		p.sawColor = true
		text = text[index+len(attachProbeColorQuery):]
	}
	if strings.Contains(text, attachProbeCursorQuery) {
		return true, true
	}
	p.pending = suffix(text, len(attachProbeCursorQuery)-1)
	return false, false
}

func suffix(value string, n int) string {
	if len(value) <= n {
		return value
	}
	return value[len(value)-n:]
}

// enqueueReply queues terminal-generated bytes behind any pending input,
// using the same bounded queue as viewer input. It never blocks.
func (r *run) enqueueReply(data string) bool {
	size := int64(len(data))
	if r.inputBytes.Add(size) > 2<<20 {
		r.inputBytes.Add(-size)
		return false
	}
	select {
	case r.input <- data:
		return true
	default:
		r.inputBytes.Add(-size)
		return false
	}
}
